					),
				),
				'metaCustomId'        => array(
					'type'    => 'customId',
					'access'  => 'public',
					'value'   => '',
					'options' => array(
						'label'       => 'Element ID',
						'description' => 'Apply a unique ID to the element to link it directly by using #your_id (for element ID use lowercase input only).',
					),
				),
				'designOptions'       => array(
					'type'    => 'designOptions',
					'access'  => 'public',
					'value'   => array(),
					'options' => array(
						'label' => 'Design Options',
					),
				),
				'styleEditor'         => array(
					'type'    => 'styleEditor',
					'access'  => 'public',
					'value'   => array(),
					'options' => array(),
				),
				'extraDataAttributes' => array(
					'type'    => 'string',
					'access'  => 'public',
					'value'   => '',
					'options' => array(
						'label'       => 'Extra Data Attributes',
						'description' => 'Add data attributes to your element (ex. data-name="John Lennon" data-age="28")',
					),
				),
				'htmlAttributes'      => array(
					'type'    => 'group',
					'access'  => 'public',
					'value'   => array( 'metaCustomId', 'customClass' ),
