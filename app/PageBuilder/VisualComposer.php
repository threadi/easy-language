	}

	/**
	 * Return a single attribute for Visual Composer from a field definition.
	 *
	 * @param array<string,mixed>               $field The field definition.
	 * @param array<string,array<string,mixed>> $fields All field definitions.
	 *
	 * @return array<string,mixed>
	 */
	private function get_attribute( array $field, array $fields ): array {
		$attribute = array(
			'access'  => 'public',
			'options' => array(
				'label' => $field['label'] ?? '',
			),
		);

		// add the description.
		if ( ! empty( $field['description'] ) ) {
			$attribute['options']['description'] = $field['description'];
		}

		// add the field type specific settings.
		switch ( $field['type'] ) {
			case 'select':
				$attribute['type']              = 'dropdown';
				$attribute['value']             = (string) $field['default'];
				$attribute['options']['values'] = array();
				foreach ( is_array( $field['options'] ?? null ) ? $field['options'] : array() as $value => $label ) {
					$attribute['options']['values'][] = array(
						'label' => (string) $label,
						'value' => (string) $value,
					);
				}
				break;

			case 'switch':
				$attribute['type']  = 'toggle';
				$attribute['value'] = ! empty( $field['default'] );
				break;

			case 'color':
				$attribute['type']  = 'color';
				$attribute['value'] = is_string( $field['default'] ) ? $field['default'] : '';
				break;

			case 'objects':
				// search the objects via autocomplete (saved as comma separated list like "post:12,term:5").
				$attribute['type']                   = 'autocomplete';
				$attribute['value']                  = '';
				$attribute['options']['action']      = self::AUTOCOMPLETE_ACTION;
				$attribute['options']['labelAction'] = self::AUTOCOMPLETE_ACTION;
				$attribute['options']['validation']  = true;
				break;

			default:
				// use a text field for sizes (e.g. "24px") and all other types.
				$attribute['type']  = 'string';
				$attribute['value'] = is_scalar( $field['default'] ) ? (string) $field['default'] : '';
		}

		// add the conditions.
		$rules = $this->get_rules( $field, $fields );
		if ( ! empty( $rules ) ) {
			$attribute['options']['onChange'] = array(
				'rules'   => $rules,
				'actions' => array(
					array(
						'action' => 'toggleVisibility',
					),
				),
			);
		}

		// return the resulting attribute.
		return $attribute;
	}

	/**
	 * Return the rules to show a field depending on other fields.
	 *
	 * @param array<string,mixed>               $field The field definition.
	 * @param array<string,array<string,mixed>> $fields All field definitions.
	 *
	 * @return array<string,array<string,mixed>>
	 */
	private function get_rules( array $field, array $fields ): array {
		$rules = array();
		foreach ( isset( $field['condition'] ) && is_array( $field['condition'] ) ? $field['condition'] : array() as $controller => $allowed_values ) {
			// bail if the controlling field does not exist.
			if ( ! isset( $fields[ $controller ] ) ) {
				continue;
			}

			// use the rule "toggle" for switches (only possible if the field is shown for enabled switches).
			if ( 'switch' === $fields[ $controller ]['type'] ) {
				if ( in_array( true, (array) $allowed_values, true ) && ! in_array( false, (array) $allowed_values, true ) ) {
					$rules[ $controller ] = array( 'rule' => 'toggle' );
				}
				continue;
			}

			// use the rule "valueIn" for all other fields.
			$rules[ $controller ] = array(
				'rule'    => 'valueIn',
				'options' => array(
					'values' => array_values( array_map( 'strval', (array) $allowed_values ) ),
				),
			);
		}
		return $rules;
	}

	/**
	 * Return the search results for the visibility objects in the autocomplete field.
	 *
	 * @param mixed $response The response.
	 * @param mixed $payload The payload with the search value.
	 *
	 * @return mixed
	 */
	public function get_autocomplete_results( mixed $response, mixed $payload ): mixed {
		// bail if the response is not an array.
		if ( ! is_array( $response ) ) {
			$response = array();
		}

		// get the search value.
		$search = is_array( $payload ) && isset( $payload['searchValue'] ) && is_string( $payload['searchValue'] ) ? $payload['searchValue'] : '';

		// search the objects.
		$results = array();
		foreach ( Switcher::get_instance()->search_objects( $search, 20 ) as $object ) {
			$results[] = array(
				'value' => $object['value'],
				'label' => $object['label'],
			);
		}

		// return the results.
		$response['status']  = true;
		$response['results'] = $results;
		return $response;
	}

	/**
	 * Return the labels for the chosen visibility objects in the autocomplete field.
	 *
	 * @param mixed $response The list of labels (token => label).
	 * @param mixed $payload The payload with the action and the token.
	 *
	 * @return mixed
	 */
	public function get_autocomplete_labels( mixed $response, mixed $payload ): mixed {
		// bail if this is not our action.
		if ( ! is_array( $response ) || ! is_array( $payload ) || ! isset( $payload['action'], $payload['token'] ) || self::AUTOCOMPLETE_ACTION !== $payload['action'] ) {
			return $response;
		}

		// get the label of the object.
		$token = (string) $payload['token'];
		foreach ( Switcher::get_instance()->get_object_labels( array( $token ) ) as $object ) {
			$response[ $token ] = $object['label'];
		}

		// return the labels.
		return $response;
	}

	/**
	 * Return the output of our shortcode.
	 *
	 * @param array<string,mixed>|string $attributes The attributes of the shortcode (empty string if none is set).
	 *
	 * @return string
	 */
	public function render_shortcode( array|string $attributes ): string {
		// WordPress uses an empty string if no attributes are set.
		if ( ! is_array( $attributes ) ) {
			$attributes = array();
		}

		// return the output in frontend.
		$switcher = Switcher::get_instance();
		if ( ! $this->is_preview() ) {
			return $switcher->render_widget( $attributes, 'visualcomposer', false );
		}

		// the editor renders the preview via AJAX without a queried object: use the edited post for it.
		global $wp_query;
		$original_query = $wp_query;
		$post_id        = isset( $_REQUEST['vcv-source-id'] ) ? absint( $_REQUEST['vcv-source-id'] ) : 0; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- nonce is checked by Visual Composer.
		$post           = get_post( $post_id );
		if ( $post instanceof WP_Post && 0 === get_queried_object_id() ) {
			$wp_query                    = new WP_Query(); // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited
			$wp_query->queried_object    = $post;
			$wp_query->queried_object_id = $post->ID;
		}

		// get the output.
		$output = $switcher->render_widget( $attributes, 'visualcomposer', true );

		// restore the original query.
		$wp_query = $original_query; // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited

		// return the output.
		return $output;
	}

	/**
	 * Return whether the shortcode is rendered as preview in the editor of Visual Composer.
	 *
	 * The editor renders shortcodes via its own AJAX requests (e.g. "elements:ajaxShortcode:adminNonce").
	 *
	 * @return bool
	 */
	private function is_preview(): bool {
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- nonce is checked by Visual Composer.
		$action = isset( $_REQUEST['vcv-action'] ) ? sanitize_text_field( wp_unslash( $_REQUEST['vcv-action'] ) ) : '';
		return str_starts_with( $action, 'elements:ajaxShortcode' );
	}
}
