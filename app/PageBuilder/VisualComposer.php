/**
 * File to handle support for the page builder Visual Composer Website Builder.
 *
 * @package easy-language
 */

namespace easyLanguage\PageBuilder;

// deny direct access.
defined( 'ABSPATH' ) || exit;

use easyLanguage\EasyLanguage\PageBuilder_Base;
use easyLanguage\EasyLanguage\Switcher;
use easyLanguage\Plugin\Helper;
use WP_Post;
use WP_Query;

/**
 * Object to handle support for the page builder Visual Composer Website Builder.
 *
 * Adds the element "Language Switcher" to Visual Composer via its official API for third party elements
 * (action "vcv:api" with $api->elements->add()). The element (manifest, images and a hand-written element bundle
 * without build step) is located in legacy-classes/VisualComposer/easyLanguageSwitcher/.
 *
 * The element bundle gets its settings from the variable VCV_EASY_LANGUAGE_SWITCHER which we generate here from the
 * field definitions of the switcher. In the editor, the element renders our shortcode via the shortcode preview of
 * Visual Composer. Visual Composer saves the shortcode in the content of the page, so the output in frontend is
 * generated by the shortcode.
 */
class VisualComposer extends PageBuilder_Base {
	/**
	 * The tag of our element in Visual Composer.
	 */
	public const ELEMENT_TAG = 'easyLanguageSwitcher';

	/**
	 * The name of the shortcode used by our element.
	 */
	public const SHORTCODE = 'easy_language_vc_switcher';

	/**
	 * The name of the autocomplete action for the visibility objects.
	 */
	private const AUTOCOMPLETE_ACTION = 'easyLanguageObjects';

	/**
	 * Instance of this object.
	 *
	 * @var ?VisualComposer
	 */
	private static ?VisualComposer $instance = null;

	/**
	 * Constructor for this object.
	 */
	private function __construct() {}

	/**
	 * Prevent cloning of this object.
	 *
	 * @return void
	 */
	private function __clone() {}

	/**
	 * Return the instance of this Singleton object.
	 */
	public static function get_instance(): VisualComposer {
		if ( is_null( self::$instance ) ) {
			self::$instance = new self();
		}

		return self::$instance;
	}

	/**
	 * Initialize this object.
	 *
	 * @return void
	 */
	public function init(): void {
		add_action( 'init', array( $this, 'register_shortcode' ) );
		add_action( 'vcv:api', array( $this, 'register_element' ) );
		add_action( 'init', array( $this, 'add_filters' ) );
	}

	/**
	 * Return whether the page builder is active or not.
	 *
	 * @return bool
	 */
	public function is_active(): bool {
		return Helper::is_plugin_active( 'visualcomposer/plugin-wordpress.php' ) || defined( 'VCV_VERSION' );
	}

	/**
	 * Register the shortcode used by our element.
	 *
	 * @return void
	 */
	public function register_shortcode(): void {
		// bail if Visual Composer is not active.
		if ( ! $this->is_active() ) {
			return;
		}

		add_shortcode( self::SHORTCODE, array( $this, 'render_shortcode' ) );
	}

	/**
	 * Register our element via the API of Visual Composer.
	 *
	 * @param object $api The API object of Visual Composer.
	 *
	 * @return void
	 */
	public function register_element( object $api ): void {
		// bail if Visual Composer is not active.
		if ( ! $this->is_active() ) {
			return;
		}

		// get the elements API.
		$elements_api = $api->elements; // @phpstan-ignore property.notFound
		if ( ! is_object( $elements_api ) || ! is_callable( array( $elements_api, 'add' ) ) ) {
			return;
		}

		// add our element.
		$path = 'legacy-classes/VisualComposer/' . self::ELEMENT_TAG;
		call_user_func( array( $elements_api, 'add' ), Helper::get_plugin_path() . $path . '/manifest.json', Helper::get_plugin_url() . $path );
	}

	/**
	 * Add our filters to the filter system of Visual Composer.
	 *
	 * Visual Composer uses its own filters (not WordPress hooks) for the variables of the editor and the
	 * autocomplete fields.
	 *
	 * @return void
	 */
	public function add_filters(): void {
		// bail if Visual Composer is not active.
		if ( ! $this->is_active() || ! function_exists( 'vchelper' ) ) {
			return;
		}

		// get the filter helper of Visual Composer.
		$filters = vchelper( 'Filters' );
		if ( ! is_object( $filters ) || ! is_callable( array( $filters, 'listen' ) ) ) {
			return;
		}

		// add our variables after Visual Composer added its own (higher weight runs later).
		call_user_func( array( $filters, 'listen' ), 'vcv:editor:variables', array( $this, 'add_editor_variables' ), 100 );

		// add the search and the labels for the visibility objects.
		call_user_func( array( $filters, 'listen' ), 'vcv:autocomplete:' . self::AUTOCOMPLETE_ACTION . ':render', array( $this, 'get_autocomplete_results' ) );
		call_user_func( array( $filters, 'listen' ), 'vcv:editor:autocomplete:checkAction', array( $this, 'get_autocomplete_labels' ) );
	}

	/**
	 * Add the settings of our element to the variables of the editor and translate its name.
	 *
	 * @param mixed $response List of variables.
	 *
	 * @return mixed
	 */
	public function add_editor_variables( mixed $response ): mixed {
		// bail if the response is not an array.
		if ( ! is_array( $response ) ) {
			return $response;
		}

		// translate the name of our element in the list of elements (the manifest is not translatable).
		foreach ( $response as $index => $variable ) {
			if ( ! is_array( $variable ) || ! isset( $variable['key'] ) || 'VCV_HUB_GET_ELEMENTS' !== $variable['key'] ) {
				continue;
			}
			if ( isset( $variable['value'][ self::ELEMENT_TAG ]['settings'] ) && is_array( $variable['value'][ self::ELEMENT_TAG ]['settings'] ) ) {
				$response[ $index ]['value'][ self::ELEMENT_TAG ]['settings']['name'] = __( 'Language Switcher', 'easy-language' );
			}
		}

		// add the settings of our element.
		$response[] = array(
			'key'   => 'VCV_EASY_LANGUAGE_SWITCHER',
			'value' => array(
				'shortcode' => self::SHORTCODE,
				'fields'    => $this->get_field_types(),
				'settings'  => $this->get_element_settings(),
			),
			'type'  => 'variable',
		);

		// return the resulting list.
		return $response;
	}

	/**
	 * Return the types of our fields for the shortcode generated in the element bundle.
	 *
	 * @return array<string,string>
	 */
	private function get_field_types(): array {
		$types = array();
		foreach ( Switcher::get_instance()->get_widget_fields() as $name => $field ) {
			$types[ (string) $name ] = (string) $field['type'];
		}
		return $types;
	}

	/**
	 * Return the settings of our element in the format of Visual Composer.
	 *
	 * The settings are generated from the field definitions of the switcher, grouped by their sections.
	 *
	 * @return array<string,mixed>
	 */
	public function get_element_settings(): array {
		$switcher = Switcher::get_instance();
		$fields   = $switcher->get_widget_fields();
		$titles   = $switcher->get_widget_sections();

		// add the basic settings.
		$settings = array(
			'tag'       => array(
				'access' => 'protected',
				'type'   => 'string',
				'value'  => self::ELEMENT_TAG,
			),
			'relatedTo' => array(
				'type'   => 'group',
				'access' => 'protected',
				'value'  => array( 'General' ),
			),
		);

		// add the fields and collect them in their sections.
		$sections = array();
		foreach ( $fields as $name => $field ) {
			$settings[ $name ] = $this->get_attribute( $field, $fields );

			// add the field to its section.
			$section                = isset( $field['section'] ) ? (string) $field['section'] : 'settings';
			$sections[ $section ][] = $name;
		}

		// add the sections as groups.
		$section_groups = array();
