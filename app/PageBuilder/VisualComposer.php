				'type'    => 'group',
				'access'  => 'protected',
				'options' => array(
					'label' => $titles[ $section ] ?? $section,
				),
				'value'   => $names,
			);
			$section_groups[]        = $group_name;
		}

		// add the tabs and the default settings of elements (like other elements of Visual Composer).
		return array_merge(
			$settings,
