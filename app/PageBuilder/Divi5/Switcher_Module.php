/**
 * Object to handle the language switcher module in Divi 5.
 *
 * The settings (module metadata) are generated from the field definitions of the switcher. The values are saved in the
 * attribute "switcher.advanced.settings" of the module (one sub-attribute per field). The output in frontend is
 * generated by the switcher via the render callback, the visual builder shows the same output via a REST API request.
 */
class Switcher_Module {
	/**
	 * The name of the module.
	 */
	public const NAME = 'easy-language/divi-switcher';

	/**
	 * The name of the attribute where all switcher values are saved.
	 */
	private const ATTR_NAME = 'switcher.advanced.settings';

	/**
	 * The handle of the script for the visual builder.
	 */
	private const SCRIPT_HANDLE = 'easy-language-divi5-switcher';

	/**
	 * Instance of this object.
	 *
	 * @var ?Switcher_Module
	 */
	private static ?Switcher_Module $instance = null;

	/**
	 * Constructor for this object.
	 */
	private function __construct() {}

	/**
	 * Prevent cloning of this object.
	 *
	 * @return void
	 */
	private function __clone() {}

	/**
	 * Return the instance of this Singleton object.
	 */
	public static function get_instance(): Switcher_Module {
		if ( is_null( self::$instance ) ) {
			self::$instance = new self();
		}

		return self::$instance;
	}

	/**
	 * Register the module in Divi 5.
	 *
	 * @return void
	 */
	public function register(): void {
		$metadata = $this->get_metadata();
		ModuleRegistration::register_module(
			Helper::get_plugin_path() . 'divi5/module/',
			array(
				'title'           => $metadata['title'],
				'titles'          => $metadata['titles'],
				'attributes'      => $metadata['attributes'],
				'settings'        => $metadata['settings'],
				'render_callback' => array( $this, 'render_callback' ),
			)
		);
	}

	/**
	 * Return the metadata of the module (like a module.json of Divi 5, but generated from the switcher fields).
	 *
	 * @param bool $for_vb True to get the metadata for the visual builder (JS) with options for fields with type "objects".
	 *
	 * @return array<string,mixed>
	 */
	public function get_metadata( bool $for_vb = false ): array {
		$switcher = Switcher::get_instance();

		// empty settings must be objects in JS, but arrays in PHP.
		$empty = $for_vb ? (object) array() : array();

		// add the groups of the settings (one per section of the switcher fields).
		$groups   = array();
		$priority = 10;
		foreach ( $switcher->get_widget_sections() as $section => $title ) {
			$group_slug            = $this->get_group_slug( $section );
			$groups[ $group_slug ] = array(
				'panel'         => $this->get_panel( $section ),
				'priority'      => $priority,
				'groupName'     => $group_slug,
				'multiElements' => true,
				'component'     => array(
					'name'  => 'divi/composite',
					'props' => array(
						'groupLabel' => $title,
					),
				),
			);
			$priority             += 10;
		}

		// add the fields.
		$items    = array();
		$defaults = array();
		$priority = 10;
		foreach ( $switcher->get_widget_fields() as $name => $field ) {
			$item = array(
				'attrName'  => self::ATTR_NAME,
				'subName'   => $name,
				'label'     => $field['label'],
				'groupSlug' => $this->get_group_slug( (string) $field['section'] ),
				'priority'  => $priority,
				'render'    => true,
				'features'  => array(
					'responsive' => false,
					'hover'      => false,
					'sticky'     => false,
				),
				'component' => $this->get_component( $field, $for_vb ),
			);
			if ( ! empty( $field['description'] ) ) {
				$item['description'] = $field['description'];
			}
			$items[ $name ]    = $item;
			$defaults[ $name ] = $this->get_default_value( $field );
			$priority         += 10;
		}

		// return the resulting metadata.
		return array(
			'name'                 => self::NAME,
			'title'                => __( 'Language Switcher', 'easy-language' ),
			'titles'               => __( 'Language Switchers', 'easy-language' ),
			'moduleIcon'           => 'easy-language/divi-switcher',
			'moduleClassName'      => 'easy_language_switcher',
			'moduleOrderClassName' => 'easy_language_switcher',
			'category'             => 'module',
			'childrenName'         => array(),
			'attributes'           => array(
				'module'   => array(
					'type'     => 'object',
					'selector' => '{{selector}}',
					'default'  => array(
						'meta' => array(
							'adminLabel' => array(
								'desktop' => array(
									'value' => __( 'Language Switcher', 'easy-language' ),
								),
							),
						),
					),
					'settings' => array(
						'meta'       => array(
							'adminLabel' => $empty,
						),
						'advanced'   => array(
							'html'           => $empty,
							'htmlAttributes' => $empty,
						),
						'decoration' => array(
							'background' => $empty,
							'sizing'     => $empty,
							'spacing'    => $empty,
							'border'     => $empty,
							'boxShadow'  => $empty,
							'filters'    => $empty,
							'transform'  => $empty,
							'animation'  => $empty,
							'overflow'   => $empty,
							'disabledOn' => $empty,
							'transition' => $empty,
							'position'   => $empty,
							'zIndex'     => $empty,
							'scroll'     => $empty,
							'sticky'     => $empty,
						),
					),
				),
				'switcher' => array(
					'type'     => 'object',
					'default'  => array(
						'advanced' => array(
							'settings' => array(
								'desktop' => array(
									'value' => $defaults,
								),
							),
						),
					),
					'settings' => array(
						'advanced' => array(
							'settings' => array(
								'groupType' => 'group-items',
								'items'     => $items,
							),
						),
					),
				),
			),
			'customCssFields'      => $empty,
			'settings'             => array(
				'content'  => 'auto',
				'design'   => 'auto',
				'advanced' => 'auto',
				'groups'   => $groups,
			),
		);
	}

	/**
	 * Return the Divi 5 field component for a switcher field.
	 *
	 * @param array<string,mixed> $field               The field definition.
	 * @param bool                $with_object_options True to add the options for fields with type "objects".
	 *
	 * @return array<string,mixed>
	 */
	private function get_component( array $field, bool $with_object_options ): array {
		switch ( $field['type'] ) {
			case 'select':
				$options = array();
				foreach ( (array) $field['options'] as $value => $label ) {
					$options[ (string) $value ] = array( 'label' => $label );
				}
				return array(
					'name'  => 'divi/select',
					'type'  => 'field',
					'props' => array(
						'options' => $options,
					),
				);
			case 'switch':
				return array(
					'name' => 'divi/toggle',
					'type' => 'field',
				);
			case 'size':
				$units = ! empty( $field['units'] ) ? array_values( (array) $field['units'] ) : array( 'px' );
				return array(
					'name'  => 'divi/range',
					'type'  => 'field',
					'props' => array(
						'allowedUnits' => $units,
						'defaultUnit'  => $units[0],
						'min'          => 0,
						'max'          => 100,
						'step'         => 1,
					),
				);
			case 'color':
				return array(
					'name' => 'divi/color-picker',
					'type' => 'field',
				);
			case 'objects':
				// Divi 5 has no searchable multi select field for modules: use checkboxes with all objects.
				$options = array();
				if ( $with_object_options ) {
					foreach ( Switcher::get_instance()->search_objects( '', 500 ) as $object ) {
						$options[] = array(
							'value' => $object['value'],
							'label' => $object['label'],
						);
					}
				}
				return array(
					'name'  => 'divi/checkboxes',
					'type'  => 'field',
					'props' => array(
						'options' => $options,
					),
				);
		}

		// use a text field for any other type.
		return array(
			'name' => 'divi/text',
			'type' => 'field',
		);
	}

	/**
	 * Return the default value of a field in the format of Divi 5.
	 *
	 * @param array<string,mixed> $field The field definition.
	 *
	 * @return mixed
	 */
	private function get_default_value( array $field ): mixed {
		if ( 'switch' === $field['type'] ) {
			return $field['default'] ? 'on' : 'off';
		}
		if ( 'objects' === $field['type'] ) {
			return array_values( (array) $field['default'] );
		}
		return is_scalar( $field['default'] ) ? (string) $field['default'] : '';
	}

	/**
	 * Return the conditions of the fields for the visual builder (where the conditions are checked via JS).
	 *
	 * @return array<string,array<string,mixed>>
	 */
	private function get_conditions(): array {
		$fields     = Switcher::get_instance()->get_widget_fields();
		$conditions = array();
		foreach ( $fields as $name => $field ) {
			// bail if field has no condition.
			if ( empty( $field['condition'] ) || ! is_array( $field['condition'] ) ) {
				continue;
			}

			// collect the allowed values in the format of Divi 5.
			$condition = array();
			foreach ( $field['condition'] as $field_name => $allowed_values ) {
				$is_switch                = isset( $fields[ $field_name ] ) && 'switch' === $fields[ $field_name ]['type'];
				$condition[ $field_name ] = array_map(
					static function ( $value ) use ( $is_switch ): string {
						if ( $is_switch ) {
							return $value ? 'on' : 'off';
						}
						return is_scalar( $value ) ? (string) $value : '';
					},
					array_values( (array) $allowed_values )
				);
			}

			// add the condition with the position of the field in the settings.
			$section             = (string) $field['section'];
			$conditions[ $name ] = array(
				'panel'     => $this->get_panel( $section ),
				'groupSlug' => $this->get_group_slug( $section ),
				'condition' => $condition,
			);
		}
		return $conditions;
	}

	/**
	 * Return the slug of the settings group for a section of the switcher fields.
	 *
	 * @param string $section The section.
	 *
	 * @return string
	 */
	private function get_group_slug( string $section ): string {
		return $this->get_panel( $section ) . 'EasyLanguage' . ucfirst( sanitize_key( $section ) );
	}

	/**
	 * Return the settings panel of Divi 5 for a section of the switcher fields.
	 *
	 * @param string $section The section.
	 *
	 * @return string
	 */
	private function get_panel( string $section ): string {
		return 'design' === $section ? 'design' : 'content';
	}

	/**
	 * Return the values of the switcher from the attributes of a module.
	 *
	 * Global colors and other variables of Divi 5 are resolved to values.
	 *
	 * @param array<string,mixed> $attrs The attributes of the module.
	 *
	 * @return array<string,mixed>
	 */
	public function get_values( array $attrs ): array {
		$values = $attrs['switcher']['advanced']['settings']['desktop']['value'] ?? array();
		if ( ! is_array( $values ) ) {
			return array();
		}

		// resolve global colors and variables.
		foreach ( $values as $name => $value ) {
			if ( ! is_string( $value ) || ! str_contains( $value, '$variable(' ) ) {
				continue;
			}

			// resolve global colors (if Divi supports it).
			$resolved = null;
			if ( method_exists( Utils::class, 'resolve_global_color_to_value' ) ) {
				$resolved = Utils::resolve_global_color_to_value( $value );
			}

			// use the resolved color.
			if ( is_string( $resolved ) && ! str_contains( $resolved, '$variable(' ) ) {
				$values[ $name ] = $resolved;
				continue;
			}

			// bail if Divi does not support to resolve dynamic variables.
			if ( ! method_exists( Utils::class, 'resolve_dynamic_variable' ) ) {
				continue;
			}

			// resolve the dynamic variable.
			$values[ $name ] = Utils::resolve_dynamic_variable( $value );
		}

		// return the values.
		return $values;
	}

	/**
	 * Render the module in frontend.
	 *
	 * @param array<string,mixed> $attrs    Block attributes that were saved by the visual builder.
	 * @param string|null         $content  The rendered inner blocks (not used as the module has no children).
	 * @param WP_Block            $block    Parsed block object that is rendered.
	 * @param object              $elements ModuleElements instance.
	 *
	 * @return string
	 */
	public function render_callback( array $attrs, ?string $content, WP_Block $block, object $elements ): string { // phpcs:ignore Generic.CodeAnalysis.UnusedFunctionParameter.FoundBeforeLastUsed
		// get the output of the switcher.
		$output = Switcher::get_instance()->render_widget( $this->get_values( $attrs ), 'divi5' );

		// bail if the switcher is not visible on this page.
		if ( empty( $output ) ) {
			return '';
		}

		// get the parent.
		$parent = BlockParserStore::get_parent( $block->parsed_block['id'], $block->parsed_block['storeInstance'] );

		// return the output in the module wrapper of Divi.
		return Module::render(
			array(
				'orderIndex'          => $block->parsed_block['orderIndex'],
				'storeInstance'       => $block->parsed_block['storeInstance'],
				'attrs'               => $attrs,
				'elements'            => $elements,
				'id'                  => $block->parsed_block['id'],
				'name'                => $block->block_type->name,
				'moduleCategory'      => $block->block_type->category,
				'stylesComponent'     => array( $this, 'module_styles' ),
				'scriptDataComponent' => array( $this, 'module_script_data' ),
				'parentAttrs'         => $parent->attrs ?? array(),
				'parentId'            => $parent->id ?? '',
				'parentName'          => $parent->blockName ?? '', // phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase
				'children'            => array(
					$elements->style_components( array( 'attrName' => 'module' ) ),
					$output,
				),
			)
		);
	}

	/**
	 * Add the styles of the module (design settings of Divi like spacing or background).
	 *
	 * @param array<string,mixed> $args The arguments from Divi.
	 *
	 * @return void
	 */
	public function module_styles( array $args ): void {
		$attrs    = $args['attrs'] ?? array();
		$elements = $args['elements'];
		$settings = $args['settings'] ?? array();

		Style::add(
			array(
				'id'            => $args['id'],
				'name'          => $args['name'],
				'orderIndex'    => $args['orderIndex'],
				'storeInstance' => $args['storeInstance'],
				'styles'        => array(
					$elements->style(
						array(
							'attrName'   => 'module',
							'styleProps' => array(
								'disabledOn' => array(
									'disabledModuleVisibility' => $settings['disabledModuleVisibility'] ?? null,
								),
							),
						)
					),
					CssStyle::style(
						array(
							'selector'  => $args['orderClass'],
							'attr'      => $attrs['css'] ?? array(),
							'cssFields' => array(),
						)
					),
				),
			)
		);
	}

	/**
	 * Set the script data of the module (e.g. for animations and links of the module wrapper).
	 *
	 * @param array<string,mixed> $args The arguments from Divi.
	 *
	 * @return void
	 */
	public function module_script_data( array $args ): void {
		$attrs = $args['attrs'] ?? array();
		ElementScriptData::set(
			array(
				'id'            => $args['id'] ?? '',
				'selector'      => $args['selector'] ?? '',
				'attrs'         => array_merge(
					$attrs['module']['decoration'] ?? array(),
					array(
						'link' => $attrs['module']['advanced']['link'] ?? array(),
					)
				),
				'storeInstance' => $args['storeInstance'] ?? null,
			)
		);
	}

	/**
	 * Register the script for the visual builder of Divi 5 (app window, where the modules are registered via JS).
	 *
	 * @return void
	 */
	public function register_vb_script(): void {
		// get the asset data of the build.
		$asset_path = Helper::get_plugin_path() . 'divi5/build/index.asset.php';
		if ( ! file_exists( $asset_path ) ) {
			return;
		}
		$asset = require $asset_path;
		if ( ! is_array( $asset ) ) {
			return;
		}

		// get the ID of the edited object.
		$post_id = is_singular() ? get_queried_object_id() : 0;

		// register the script for the app window of the visual builder.
		PackageBuildManager::register_package_build(
			array(
				'name'    => self::SCRIPT_HANDLE,
				'version' => isset( $asset['version'] ) && is_string( $asset['version'] ) ? $asset['version'] : Helper::get_file_version( Helper::get_plugin_path() . 'divi5/build/index.js' ),
				'script'  => array(
					'src'                => Helper::get_plugin_url() . 'divi5/build/index.js',
					'deps'               => array(
						'divi-module-library',
						'divi-module',
						'divi-vendor-wp-hooks',
						'divi-vendor-react',
					),
					'enqueue_top_window' => false,
					'enqueue_app_window' => true,
					'data_app_window'    => array(
						'metadata'   => $this->get_metadata( true ),
						'conditions' => $this->get_conditions(),
						'attrName'   => self::ATTR_NAME,
						'previewUrl' => rest_url( 'easy-language/v1/divi5-switcher-preview' ),
						'nonce'      => wp_create_nonce( 'wp_rest' ),
						'postId'     => $post_id,
						'loading'    => __( 'Loading …', 'easy-language' ),
						'icon'       => Helper::get_plugin_url() . 'gfx/easy-language-icon.svg',
					),
				),
			)
		);
	}

	/**
	 * Register the REST API route for the preview of the module in the visual builder.
	 *
	 * @return void
	 */
	public function register_rest_route(): void {
		register_rest_route(
			'easy-language/v1',
			'/divi5-switcher-preview',
			array(
				'methods'             => WP_REST_Server::CREATABLE,
				'callback'            => array( $this, 'rest_preview' ),
				'permission_callback' => function () {
					return current_user_can( 'edit_posts' );
				},
				'args'                => array(
					'post_id' => array(
						'type'    => 'integer',
						'default' => 0,
					),
					'attrs'   => array(
						'type'    => 'object',
						'default' => array(),
					),
				),
			)
		);
	}

	/**
	 * Return the preview of the module for the visual builder.
	 *
	 * The global query is set to the edited object, so the switcher shows the languages of this object.
	 *
	 * @param WP_REST_Request $request The request.
	 *
	 * @return array<string,string>
	 */
	public function rest_preview( WP_REST_Request $request ): array {
		global $wp_query, $post;

		// get the attributes of the module.
		$attrs = $request->get_param( 'attrs' );
		if ( ! is_array( $attrs ) ) {
			$attrs = array();
		}

		// set the query to the edited object.
		$post_id        = absint( $request->get_param( 'post_id' ) );
		$original_query = $wp_query;
		$original_post  = $post;
		if ( $post_id > 0 && current_user_can( 'edit_post', $post_id ) ) {
			$wp_query = new WP_Query( // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited
				array(
					'p'           => $post_id,
					'post_type'   => 'any',
					'post_status' => 'any',
				)
			);
			$post     = get_post( $post_id ); // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited
		}

		// get the output.
		$html = Switcher::get_instance()->render_widget( $this->get_values( $attrs ), 'divi5', true );

		// restore the query.
		$wp_query = $original_query; // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited
		$post     = $original_post; // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited

		// return the output.
		return array(
			'html' => $html,
		);
	}
}
