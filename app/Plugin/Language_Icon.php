<?php
/**
 * File to handle a single icon for a language.
 *
 * @package easy-language
 */

namespace easyLanguage\Plugin;

// prevent direct access.
defined( 'ABSPATH' ) || exit;

use WP_Post;

/**
 * Object to handle a single icon.
 */
class Language_Icon {

	/**
	 * Attachment-ID.
	 *
	 * @var int
	 */
	private int $id;

	/**
	 * Path to a local file.
	 *
	 * @var string
	 */
	private string $file;

	/**
	 * Set lokal file.
	 *
	 * @param string $img The file with a path as a string.
	 *
	 * @return void
	 */
	public function set_file( string $img ): void {
		$this->file = $img;
	}

	/**
	 * Save the icon in media db as an attachment.
	 *
	 * @param string $language_code The language-code.
	 *
	 * @return void
	 */
	public function save( string $language_code ): void {
		global $wp_filesystem;

		// bail if a file is not given.
		if ( empty( $this->file ) ) {
			return;
		}

		// get path.
		$path = trailingslashit( Helper::get_plugin_path() ) . 'gfx/' . $this->file;
		$file = $this->file;
		/**
		 * Get the path where the icon files are located.
		 *
		 * @since 2.0.0 Available since 2.0.0.
		 *
		 * @param string $path The path.
		 * @param string $file The actual icon file.
		 */
		$img_path = apply_filters( 'easy_language_icon_path', $path, $file );

		// bail if a file does not exist.
		if ( empty( $img_path ) || ! Helper::get_wp_filesystem( true )->exists( $img_path ) ) {
			return;
		}
		// check if the file exists in db as icon generated by this plugin (and not e.g. by a user with the same file name).
		$attachment = $this->get_own_attachment( pathinfo( $img_path, PATHINFO_FILENAME ) );

		// if an attachment for this file does not exist, check also for post-meta.
		if ( false === $attachment ) {
			$attachment = Helper::get_attachment_by_language_code( $language_code );
		}

		// if no attachment could be found, add it.
		if ( false === $attachment ) {
			// set the import path.
			$import_path = trailingslashit( get_temp_dir() ) . $this->file;

			// allow SVG-files.
			add_filter( 'upload_mimes', array( $this, 'allow_svg' ) );

			// copy the original to the import_path.
			$wp_filesystem = Helper::get_wp_filesystem();
			if ( $wp_filesystem->copy( $img_path, $import_path ) ) {
				// Prepare an array of post-data for the attachment.
				$attachment = array(
					'name'     => basename( $this->file ),
					'tmp_name' => $import_path,
				);

				// load necessary functions for media_handle_sideload (they are not loaded e.g. in frontend or via WP CLI).
				require_once ABSPATH . 'wp-admin/includes/file.php';
				require_once ABSPATH . 'wp-admin/includes/media.php';
				require_once ABSPATH . 'wp-admin/includes/image.php';

				// Insert the attachment to prevent removing the original file and get its attachment ID.
				$attachment_id = media_handle_sideload( $attachment, 0, null, array( 'post_author' => get_current_user_id() ) );

				// get attachment as an object.
				if ( ! is_wp_error( $attachment_id ) && absint( $attachment_id ) > 0 ) {
					$attachment = get_post( absint( $attachment_id ) );
				}

				// remove the temporary file if it still exists (e.g. if the import failed).
				if ( Helper::get_wp_filesystem( true )->exists( $import_path ) ) {
					wp_delete_file( $import_path );
				}
			}

			// remove SVG as allowed files.
			remove_filter( 'upload_mimes', array( $this, 'allow_svg' ) );
		}

		// bail if attachment does still not exist.
		if ( ! $attachment instanceof WP_Post || 'attachment' !== $attachment->post_type ) {
			return;
		}

		// secure attachment-ID in an object.
		$this->set_id( $attachment->ID );

		// mark this icon as generated by this plugin.
		update_post_meta( $attachment->ID, 'easy_language_icon', 1 );

		// get the actual list of languages mapped to this icon.
		$language_list = get_post_meta( $attachment->ID, 'easy_language_code', true );
		if ( ! is_array( $language_list ) ) {
			$language_list = array();
		}

		if ( empty( $language_list[ $language_code ] ) ) {
			// add language-code to this icon.
			$language_list[ $language_code ] = 1;
			update_post_meta( $attachment->ID, 'easy_language_code', $language_list );
		}

		$instance = $this;
		/**
		 * Hook for further info for the icon.
		 *
		 * @since 2.0.0 Available since 2.0.0.
		 *
		 * @param Language_Icon $instance The language icon object.
		 */
		do_action( 'easy_language_update_icon', $instance );

		// clear icon cache in DB.
		delete_option( 'easy_language_icons' );
	}

	/**
	 * Return the attachment for the given file name, which has been generated by this plugin.
	 *
	 * Searches by the name and, as the name could be changed by WordPress if it is already used, by the title.
	 *
	 * @param string $name The file name without extension.
	 *
	 * @return WP_Post|false
	 */
	private function get_own_attachment( string $name ): WP_Post|false {
		foreach ( array( 'name', 'title' ) as $field ) {
			$query = array(
				'posts_per_page' => 1,
				'post_type'      => 'attachment',
				'post_status'    => 'inherit',
				$field           => trim( $name ),
				// phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_query -- the language icons are identified via attachment meta, there is no other way to query them
				'meta_query'     => array(
					array(
						'key'     => 'easy_language_icon',
						'value'   => '1',
						'compare' => '=',
					),
				),
			);
			$result = new \WP_Query( $query );

			// bail on no results.
			if ( 0 === $result->post_count ) {
				continue;
			}

			// return the first result.
			$post = $result->posts[0];
			if ( $post instanceof WP_Post ) {
				return $post;
			}
		}

		// return false if no attachment could be found.
		return false;
	}

	/**
	 * Get attachment-ID.
	 *
	 * @return int
	 */
	public function get_id(): int {
		return $this->id;
	}

	/**
	 * Set attachment-ID.
	 *
	 * @param int $attachment_id The attachment-ID for the file.
	 * @return void
	 */
	private function set_id( int $attachment_id ): void {
		$this->id = $attachment_id;
	}

	/**
	 * Allow SVG as a file-type.
	 *
	 * @param array<string,string> $file_types List of allowed file types.
	 *
	 * @return array<string,string>
	 */
	public function allow_svg( array $file_types ): array {
		$new_filetypes        = array();
		$new_filetypes['svg'] = 'image/svg+xml';
		return array_merge( $file_types, $new_filetypes );
	}
}
